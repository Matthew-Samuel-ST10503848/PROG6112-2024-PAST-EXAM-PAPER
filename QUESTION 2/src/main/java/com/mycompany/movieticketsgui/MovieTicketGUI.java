    private void mnuProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mnuProcessActionPerformed
        try {

        // Get the information entered by the customer
        String movieName = cmbMovie.getSelectedItem().toString();

        int numberOfTickets = Integer.parseInt(txtTicketNumber.getText());

        double ticketPrice = Double.parseDouble(txtTicketPrice.getText());

        // Create the data object
        MovieTicketData data = new MovieTicketData(
                movieName, numberOfTickets, ticketPrice);

        // Create the MovieTickets object
        MovieTickets movieTickets = new MovieTickets();

        // Validate the information
        if (movieTickets.ValidateData(data)) {

            // Calculate the subtotal
            double subtotal = numberOfTickets * ticketPrice;

            // Calculate VAT
            double vat = subtotal * 0.14;

            // Calculate total price including VAT
            double total = movieTickets.CalculateTotalTicketPrice(
                    numberOfTickets, ticketPrice);

            // Build the report
            String report = "MOVIE TICKET SALES REPORT\n"
                    + "--------------------------------\n"
                    + "Movie: " + movieName + "\n"
                    + "Number of Tickets: " + numberOfTickets + "\n"
                    + "Ticket Price: R" + String.format("%.2f", ticketPrice) + "\n"
                    + "Subtotal: R" + String.format("%.2f", subtotal) + "\n"
                    + "VAT (14%): R" + String.format("%.2f", vat) + "\n"
                    + "Total Price: R" + String.format("%.2f", total) + "\n"
                    + "--------------------------------";

            // Display the report
            txtReport.setText(report);

            // Save the report to a text file
            try (FileWriter writer = new FileWriter("report.txt")) {
                writer.write(report);
            }

            JOptionPane.showMessageDialog(this,
                    "Report saved successfully!");

        } else {

            JOptionPane.showMessageDialog(this,
                    "Please enter valid information.");

        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Please enter numbers for tickets and ticket price.");

    } catch (IOException e) {

        JOptionPane.showMessageDialog(this,
                "Error saving the report.");

    }
    }//GEN-LAST:event_mnuProcessActionPerformed

